/** "מה חדש" מוצג רק כשמשתנה הגרסה הראשית (2.0, 2.1), לא בתיקונים קטנים */
export const releaseOf = (v?: string) => (v ?? '').split('.').slice(0, 2).join('.');

const cmp = (a: string, b: string) => {
  const [a1, a2] = a.split('.').map(Number);
  const [b1, b2] = b.split('.').map(Number);
  return a1 - b1 || a2 - b2;
};

/** הגרסאות הראשיות שעוד לא הוצגו למי שראה את seen. בלי גרסה ידועה: רק האחרונה */
export function releasesSince(seen?: string): ReleaseNotes[] {
  const r = releaseOf(seen);
  if (!r) return RELEASES.slice(0, 1);
  return RELEASES.filter((x) => cmp(x.release, r) > 0);
}

